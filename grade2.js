  const RUN=/[A-Za-z0-9_"'+#][A-Za-z0-9_ "'().,=+\-*\/<>!:#%]*[A-Za-z0-9_"')+#:]|[A-Za-z0-9_]/g;
  const cnt=(s,ch)=>s.split(ch).length-1;
  const wrap=t=>t.replace(RUN,m=>{
    let tail="";
    while(m.endsWith(")")&&cnt(m,")")>cnt(m,"(")){m=m.slice(0,-1);tail=")"+tail}
    return "\u2066"+m+"\u2069"+tail;
  });
  G2PY.forEach(c=>c.lessons.forEach(l=>l[1].forEach(q=>{q[0]=wrap(q[0]);if(q[1])q[1]=wrap(q[1])})));
